import test from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {chromium} from 'playwright-core';
const root=new URL('../',import.meta.url).pathname.replace(/^\/(.:)/,'$1');
const python=process.env.PYTHON||`${root}/.venv/Scripts/python.exe`;
test('selected images animate without approval buttons, banners or review writes',{timeout:90000},async t=>{
  const child=spawn(python,['tests/still_approval_fixture_server.py'],{cwd:root,windowsHide:true,stdio:['ignore','pipe','pipe']});t.after(()=>child.kill());
  const f=await new Promise((resolve,reject)=>{let output='';const timer=setTimeout(()=>reject(Error(output)),20000);child.stdout.on('data',x=>{output+=x;const m=output.match(/READY (\S+) (\S+)/);if(m){clearTimeout(timer);resolve({url:m[1],pid:m[2]});}});child.stderr.on('data',x=>output+=x);});
  const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});t.after(()=>browser.close());
  const page=await browser.newPage({viewport:{width:1500,height:1100}}),errors=[],reviews=[],commands=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/stills\/approve-all|generations\/[^/]+\/review$/.test(r.url()))reviews.push(r.url());});
  await page.route('**/bridge/v1/command',async route=>{commands.push(route.request().postDataJSON());await route.fulfill({json:{command_id:'test-only'}});});
  await page.goto(f.url);await page.locator('#project-select').selectOption(f.pid);
  await page.getByTestId('animation-test-cloud-2').waitFor();
  assert.equal(await page.getByTestId('approve-all-stills').count(),0);
  assert.equal(await page.locator('.still-review-banner,.still-review-actions,.still-review-status').count(),0);
  const before=await (await fetch(f.url+'/api/projects/'+f.pid)).json();
  assert.equal(before.still_approval_required,false);
  assert.ok(before.scenes.every(s=>s.still_approval.status==='pending_review'));
  for(let position=1;position<=4;position++)assert.equal(await page.getByTestId('animation-test-cloud-'+position).isDisabled(),false);
  const alternative=before.generations.find(g=>g.scene_id===before.scenes[1].id&&g.purpose==='scene'&&g.id!==before.scenes[1].active_generation_id&&g.state==='succeeded');
  await page.getByTestId('select-variant-'+alternative.id).click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('выбран вариант'));
  assert.equal(await page.getByTestId('animation-test-cloud-2').isDisabled(),false);
  await page.getByTestId('animation-test-cloud-2').click();
  await page.waitForFunction(()=>document.querySelector('#notice').textContent.includes('Кадр 2: Omni отправлен'));
  const jobs=await (await fetch(f.url+'/api/projects/'+f.pid+'/animation/jobs')).json();
  assert.equal(jobs.jobs.length,1);assert.equal(jobs.jobs[0].scene_id,before.scenes[1].id);
  assert.equal(jobs.jobs[0].source_image_asset_id,alternative.asset_id);
  assert.deepEqual(commands.map(c=>c.scene_ids),[[before.scenes[1].id]]);
  assert.deepEqual(reviews,[]);assert.deepEqual(errors,[]);
  const after=await (await fetch(f.url+'/api/projects/'+f.pid)).json();
  assert.ok(after.scenes.every(s=>s.still_approval.status==='pending_review'));
  console.log('No mandatory approval; selected alternative queued with no review calls.');
});
